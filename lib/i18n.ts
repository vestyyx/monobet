// Parameterized server errors — translate the fixed prefix, keep the payload.
const ERR_CS_PREFIX: [string, (rest: string) => string][] = [
  ["Too fast", () => ERR_CS["Too fast — wait a few minutes"]],
  ["House blocklist hit: ", (r) => `Toto je na bloklistě: „${r}"`],
  ["Max leverage on this market is ", (r) => `Maximální páka na tomto trhu je ${r}`],
  ["Category is used by ", (r) => `Kategorii používá ${r.replace(/ market\(s\)$/, "")} trhů`],
  ['Bad image URL for "', (r) => `Neplatná URL obrázku pro "${r.replace(/"$/, "")}"`],
  ['Image too large for "', (r) => `Obrázek je příliš velký pro "${r.replace(/"$/, "")}"`],
  ["Max trade for you here is Ɱ ", (r) => `Tady pro tebe je maximálně Ɱ ${r}`],
  ["Max trade is Ɱ ", (r) => `Maximální obchod je Ɱ ${r}`],
];

export function serverErr(lang: Lang, msg?: string | null): string {
  const m = msg ?? "Error";
  if (lang !== "cs") return m;
  const exact = ERR_CS[m];
  if (exact) return exact;
  const handle = m.match(/^@(\S+) is taken$/);
  if (handle) return `@${handle[1]} je zabrané`;
  for (const [prefix, render] of ERR_CS_PREFIX) if (m.startsWith(prefix)) return render(m.slice(prefix.length));
  return m;
}
